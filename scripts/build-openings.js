#!/usr/bin/env node
/**
 * Builds src/renderer/data/openings.js from the lichess opening database
 * (https://github.com/lichess-org/chess-openings, CC0-1.0).
 * Every position along every named line becomes a "book" position; line
 * endpoints also carry the opening name.  Run manually when updating data:
 *   node scripts/build-openings.js
 */
const fs = require('fs');
const path = require('path');
const { Chess } = require('chess.js');

const URL = 'https://raw.githubusercontent.com/lichess-org/chess-openings/master/';

/** Position key: piece placement + side + castling + en-passant (no clocks). */
function epd(fen) {
  return fen.split(' ').slice(0, 4).join(' ');
}

async function main() {
  const book = {}; // epd -> [eco, name] or 0 for "book, unnamed"
  let lines = 0;
  for (const f of ['a', 'b', 'c', 'd', 'e']) {
    const res = await fetch(`${URL}${f}.tsv`);
    if (!res.ok) throw new Error(`${f}.tsv: HTTP ${res.status}`);
    const rows = (await res.text()).trim().split('\n').slice(1);
    for (const row of rows) {
      const [eco, name, pgn] = row.split('\t');
      const chess = new Chess();
      chess.loadPgn(pgn);
      const sans = chess.history();
      const g = new Chess();
      sans.forEach((san, i) => {
        g.move(san);
        const key = epd(g.fen());
        if (i === sans.length - 1) book[key] = [eco, name];
        else if (!(key in book)) book[key] = 0;
      });
      lines++;
    }
  }
  const out = path.join(__dirname, '..', 'src', 'renderer', 'data', 'openings.js');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out,
    '// GENERATED by scripts/build-openings.js from lichess-org/chess-openings (CC0-1.0).\n' +
    '// Key: FEN without move clocks. Value: [ECO, name] for named lines, 0 for in-book positions.\n' +
    `export const OPENINGS = ${JSON.stringify(book)};\n`);
  console.log(`${lines} opening lines -> ${Object.keys(book).length} book positions -> ${path.relative(process.cwd(), out)}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
