#!/usr/bin/env node
/**
 * Copies third-party browser assets into src/renderer/vendor so the renderer
 * can load them over file:// without a bundler.
 *   - chess.js (BSD-2-Clause) ESM build
 *   - cburnett chess pieces (CC BY-SA 3.0) from the cm-chessboard sprite
 * Runs automatically on `npm install` (postinstall) and before `npm start`.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const vendor = path.join(root, 'src', 'renderer', 'vendor');
fs.mkdirSync(vendor, { recursive: true });

// 1. chess.js
fs.copyFileSync(
  path.join(root, 'node_modules', 'chess.js', 'dist', 'esm', 'chess.js'),
  path.join(vendor, 'chess.js'),
);

// 2. Pieces: split the sprite into one standalone SVG string per piece.
const sprite = fs.readFileSync(
  path.join(root, 'node_modules', 'cm-chessboard', 'assets', 'pieces', 'standard.svg'),
  'utf8',
);
const pieces = {};
for (const code of ['wk', 'wq', 'wr', 'wb', 'wn', 'wp', 'bk', 'bq', 'br', 'bb', 'bn', 'bp']) {
  const start = sprite.indexOf(`id="${code}"`);
  if (start < 0) throw new Error(`piece ${code} not found in sprite`);
  const gStart = sprite.lastIndexOf('<g', start);
  // find matching </g> by depth counting
  let depth = 0;
  let i = gStart;
  const re = /<g[\s>]|<\/g>/g;
  re.lastIndex = gStart;
  let m;
  while ((m = re.exec(sprite))) {
    if (m[0].startsWith('</')) depth--;
    else depth++;
    if (depth === 0) { i = m.index + 4; break; }
  }
  const g = sprite.slice(gStart, i).replace(/\s+id="[^"]*"/g, '');
  pieces[code] =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40">${g.replace(/\s+/g, ' ')}</svg>`;
}
const banner =
  '// GENERATED by scripts/prepare-assets.js — do not edit.\n' +
  '// Chess pieces by Cburnett (Wikimedia Commons), CC BY-SA 3.0,\n' +
  '// via cm-chessboard (https://github.com/shaack/cm-chessboard).\n';
fs.writeFileSync(
  path.join(vendor, 'pieces.js'),
  `${banner}export const PIECES = ${JSON.stringify(pieces, null, 2)};\n`,
);
// 2b. Extra piece sets (src/renderer/assets/pieces/<set>/wK.svg …, see LICENSE.txt there)
const setsDir = path.join(root, 'src', 'renderer', 'assets', 'pieces');
const pieceSets = { cburnett: pieces };
for (const set of fs.readdirSync(setsDir).filter((d) => fs.statSync(path.join(setsDir, d)).isDirectory()).sort()) {
  const one = {};
  for (const code of Object.keys(pieces)) {
    const file = path.join(setsDir, set, `${code[0]}${code[1].toUpperCase()}.svg`);
    one[code] = fs.readFileSync(file, 'utf8').replace(/\s+/g, ' ').trim();
  }
  pieceSets[set] = one;
}
fs.writeFileSync(
  path.join(vendor, 'piece-sets.js'),
  '// GENERATED by scripts/prepare-assets.js — do not edit. Licences: src/renderer/assets/pieces/LICENSE.txt\n' +
  `export const PIECE_SETS = ${JSON.stringify(pieceSets)};\n`,
);

// 3. Sounds: embed the .ogg files as base64 so the renderer can decode them with
//    Web Audio without file:// fetches (CC0 wood impacts by Kenney, see LICENSE.txt).
const soundDir = path.join(root, 'src', 'renderer', 'assets', 'sounds');
const sounds = {};
for (const f of fs.readdirSync(soundDir).filter((x) => x.endsWith('.ogg')).sort()) {
  sounds[f.replace(/\.ogg$/, '')] = fs.readFileSync(path.join(soundDir, f)).toString('base64');
}
fs.writeFileSync(
  path.join(vendor, 'sound-data.js'),
  `// GENERATED by scripts/prepare-assets.js from src/renderer/assets/sounds — do not edit.\nexport const SOUND_DATA = ${JSON.stringify(sounds)};\n`,
);

console.log('prepared renderer vendor assets');
